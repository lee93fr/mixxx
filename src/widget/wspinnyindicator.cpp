WSpinnyIndicator::WSpinnyIndicator(QWidget* pParent, const QString& group)
        : QWidget(pParent),
          WBaseWidget(this),
          m_pVisualPlayPosition(VisualPlayPosition::getVisualPlayPosition(group)),
          m_playPosition(group, QStringLiteral("playposition")),
          m_trackSamples(group, QStringLiteral("track_samples")),
          m_trackSampleRate(group, QStringLiteral("track_samplerate")),
          m_vinylSpeed(group,
                  QStringLiteral("vinylcontrol_speed_type"),
                  ControlFlag::AllowMissingOrInvalid) {
    setAttribute(Qt::WA_TransparentForMouseEvents);
}

void WSpinnyIndicator::setup(const QDomNode& node, const SkinContext& context) {
    m_pMarker = WImageStore::getImage(
            context.getPixmapSource(context.selectNode(node, "PathForeground")),
            context.getScaleFactor());
}

void WSpinnyIndicator::render(VSyncThread* pVSyncThread) {
    if (!isVisible()) {
        return;
    }
    double position = m_playPosition.get();
    double slipPosition;
    if (m_pVisualPlayPosition && pVSyncThread) {
        m_pVisualPlayPosition->getPlaySlipAtNextVSync(
                pVSyncThread, &position, &slipPosition);
    }
    const double samples = m_trackSamples.get();
    const double sampleRate = m_trackSampleRate.get();
    double rpm = m_vinylSpeed.get();
    if (!util_isfinite(rpm) || rpm <= 0.0) {
        rpm = MIXXX_VINYL_SPEED_33_NUM;
    }
    double angle = 0.0;
    if (util_isfinite(position) && util_isfinite(samples) && samples > 0.0 &&
            util_isfinite(sampleRate) && sampleRate > 0.0) {
        // Generated by Codex (AI). track_samples counts interleaved stereo samples;
        // use the audible position, including pitch, loops and seeks. End of AI-generated text.
        const double seconds = position * (samples / 2.0) / sampleRate;
        angle = std::remainder(seconds * rpm * 6.0, 360.0);
        if (!util_isfinite(angle)) {
            angle = 0.0;
        }
    }
    if (angle != m_angle) {
        m_angle = angle;
        update();
    }
}

void WSpinnyIndicator::paintEvent(QPaintEvent* pEvent) {
    Q_UNUSED(pEvent);
    if (!m_pMarker || m_pMarker->isNull()) {
        return;
    }
    QPainter painter(this);
    painter.setRenderHint(QPainter::SmoothPixmapTransform);
    painter.translate(width() / 2.0, height() / 2.0);
    painter.rotate(m_angle);
    painter.drawImage(QRectF(-width() / 2.0, -height() / 2.0, width(), height()), *m_pMarker);
}
